#!/usr/bin/env python3
"""Embed the mod generator's VS Code templates into the game.

`vibebuild32 --gen-ts <name>` / `--gen-js <name>` writes a `.vscode/` folder
into every new mod project. The files it writes live next to this script in
`vscode/`. Run this script after editing any of them; it regenerates
`source/vibebuild32/src/vbjs_templates.inc`, which is compiled into the game.

    python3 source/vibebuild32/rsrc/modtemplate/embed.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, 'vscode')
TARGET = os.path.normpath(os.path.join(HERE, '..', '..', 'src', 'vbjs_templates.inc'))

# Written in this order by the generator.
FILES = [
    'launch.json',
    'tasks.json',
    'README.md',
    'vibebuild32-debug-adapter.js',
    'vibebuild32-start-debug-adapter.js',
]

DELIMITER = 'VBTPL'
CHUNK = 12000  # keep each literal well below common compiler limits


def literal(text):
    assert ')' + DELIMITER + '"' not in text
    parts = [text[i:i + CHUNK] for i in range(0, len(text), CHUNK)] or ['']
    return '\n      '.join('R"%s(%s)%s"' % (DELIMITER, part, DELIMITER) for part in parts)


def main():
    out = [
        '// Generated by source/vibebuild32/rsrc/modtemplate/embed.py. Do not edit;',
        '// change the files in source/vibebuild32/rsrc/modtemplate/vscode/ and rerun it.',
        '',
        'static const struct { const char *name; const char *text; } k_vbjsVscodeTemplates[] = {',
    ]
    for name in FILES:
        with open(os.path.join(SOURCE, name), encoding='utf-8', newline='') as f:
            text = f.read().replace('\r\n', '\n')
        out.append('    { "%s",\n      %s },' % (name, literal(text)))
    out.append('};')
    out.append('')
    with open(TARGET, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', os.path.relpath(TARGET))


if __name__ == '__main__':
    main()
